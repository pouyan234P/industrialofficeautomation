using Microsoft.Extensions.Diagnostics.HealthChecks;
using Serilog;
using Shared.Infrastructure.HealthChecks;
using Shared.Infrastructure.Logging;
using Shared.Infrastructure.Middleware;
using workflow.Api.Rabbit;
using workflow.Appliction;
using workflow.Persistence;
var builder = WebApplication.CreateBuilder(args);
// ?? 1. Serilog ????????????????????????????????????????????????????????????????
builder.AddSerilog("WorkflowService");

// ?? 2. Application + Persistence ?????????????????????????????????????????????
builder.Services.ConfigureApplicationService();
builder.Services.configurePersistenceServices(builder.Configuration);

// ?? 3. RabbitMQ consumers (BackgroundServices) ???????????????????????????????
// These consume the myreferral and updatereferral queues.
// Both consumers already have DLQ, retry, and structured logging built in
// from the resilience batch.
builder.Services.AddHostedService<RabbitMQreferralConsumer>();
builder.Services.AddHostedService<RabbitMQupdatereferralConsumer>();

// ?? 4. Health checks ??????????????????????????????????????????????????????????
// Requires AspNetCore.HealthChecks.MongoDb and .Rabbitmq in the .csproj.

builder.Services.AddServiceHealthChecks(hc =>
{
    

    hc.AddMongoDb(
        // Modern package requirement: Use a factory to instantiate the driver
        clientFactory: sp => new MongoDB.Driver.MongoClient(builder.Configuration.GetConnectionString("MongoSettings")!),
        name: "mongodb",
        failureStatus: HealthStatus.Degraded,
        tags: ["db", "mongo"]
    );
    hc.AddRabbitMQ(
        // Modern package requirement: Use a factory to instantiate the connection
        sp =>
        {
            var factory = new RabbitMQ.Client.ConnectionFactory()
            {
                Uri = new Uri(builder.Configuration["RabbitMQ:ConnectionString"]!)
            };

            // v9 packages use RabbitMQ.Client v7+, which requires Async creation.
            return factory.CreateConnectionAsync().GetAwaiter().GetResult();
        },
        name: "rabbitmq",
        failureStatus: HealthStatus.Degraded,
        tags: ["messaging"]
    );

});

builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();

var app = builder.Build();

// ?? 5. Serilog request logging ????????????????????????????????????????????????
app.UseSerilogRequestLogging();

// ?? 6. Correlation ID ?????????????????????????????????????????????????????????
app.UseMiddleware<CorrelationIdMiddleware>();

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.UseHttpsRedirection();
app.UseAuthorization();
app.MapControllers();

// ?? 7. Health endpoints ???????????????????????????????????????????????????????
// GET /health       ? checks MongoDB + RabbitMQ
// GET /health/live  ? always 200 (used by Docker/Kubernetes liveness probe)
app.MapHealthEndpoints();

try
{
    Log.Information("Starting WorkflowService");
    app.Run();
}
catch (Exception ex)
{
    Log.Fatal(ex, "WorkflowService failed to start");
}
finally
{
    Log.CloseAndFlush();
}
