using Ocelot.DependencyInjection;
using Ocelot.Middleware;
using Serilog;
using Shared.Infrastructure.Logging;
using Shared.Infrastructure.Middleware;

var builder = WebApplication.CreateBuilder(args);
// ?? 1. Serilog ????????????????????????????????????????????????????????????????
// Gateway logs every route it forwards, every error, and every correlation ID.
builder.AddSerilog("Gateway");

// ?? 2. Ocelot configuration ???????????????????????????????????????????????????
// Load the Ocelot routes from appsettings.json.
// The appsettings.json file already has all routes — no changes needed there.
builder.Configuration
    .SetBasePath(builder.Environment.ContentRootPath)
    .AddJsonFile("appsettings.json", optional: false, reloadOnChange: true)
    .AddJsonFile($"appsettings.{builder.Environment.EnvironmentName}.json", optional: true)
    .AddEnvironmentVariables();
var ocelotConfig = builder.Configuration.GetSection("Ocelot");
builder.Services.AddOcelot(ocelotConfig);

builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();

var app = builder.Build();

// ?? 3. Serilog request logging ????????????????????????????????????????????????
app.UseSerilogRequestLogging();

// ?? 4. Correlation ID ?????????????????????????????????????????????????????????
// The gateway is the ENTRY POINT for all client traffic.
// This middleware generates the CorrelationId (or reads one the client passed)
// and writes it to the response.
//
// Ocelot then forwards ALL request headers — including X-Correlation-Id —
// to the downstream service automatically. This is how the single ID
// generated here propagates to Correspondence, Workflow, Search, and AI services.
app.UseMiddleware<CorrelationIdMiddleware>();

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

// ?? 5. Ocelot pipeline ????????????????????????????????????????????????????????
// UseOcelot() must come AFTER the correlation ID middleware so the ID is
// already in the request headers when Ocelot forwards them downstream.
await app.UseOcelot();

app.MapControllers();

try
{
    Log.Information("Starting Gateway on port 5003");
    app.Run();
}
catch (Exception ex)
{
    Log.Fatal(ex, "Gateway failed to start");
}
finally
{
    Log.CloseAndFlush();
}
